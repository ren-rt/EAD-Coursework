    private void loadUsers() {
        dbcon db = new dbcon();
        Connection con = null;
        PreparedStatement stmt = null;
        ResultSet rs = null;

        try {
            con = db.open();
            if (con == null) return;

            String query = "SELECT user_id, username, password, full_name, email, role FROM users";
            stmt = con.prepareStatement(query);
            rs = stmt.executeQuery();

            DefaultTableModel model = new DefaultTableModel(
                new String[]{"User ID", "Username", "Password", "Full Name", "Email", "Role"}, 0
            );
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("user_id"),
                    rs.getString("username"),
                    rs.getString("password"),
                    rs.getString("full_name"),
                    rs.getString("email"),
                    rs.getString("role")
                });
            }
            jTable1.setModel(model);
        } catch (SQLException e) {
            System.out.println("Load users error: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Failed to load users", "ERROR", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) rs.close();
                if (stmt != null) stmt.close();
                db.close(con);
            } catch (SQLException e) {
                System.out.println("Cleanup error: " + e.getMessage());
            }
        }
    }
