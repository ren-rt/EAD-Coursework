    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        dbcon db = new dbcon();
        Connection con = null;
        PreparedStatement stmt = null;

        String userIdStr = username.getText().trim();
        if (userIdStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a user first", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int userId;
        try {
            userId = Integer.parseInt(userIdStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid User ID", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String usern = username4.getText().trim();
        
        String fullName = username3.getText().trim();
        String email = username2.getText().trim();

        if (usern.isEmpty() || fullName.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields are required", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            con = db.open();
            if (con == null) return;

            String query = "UPDATE users SET username = ?, password = ?, full_name = ?, email = ? WHERE user_id = ?";
            stmt = con.prepareStatement(query);
            stmt.setString(1, usern);
            
            stmt.setString(3, fullName);
            stmt.setString(4, email);
            stmt.setInt(5, userId);
            int rowsAffected = stmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "User updated successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                loadUsers(); // Refresh the table
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "User not found or no changes made", "ERROR", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException e) {
            System.out.println("Save error: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Failed to save changes: " + e.getMessage(), "ERROR", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (stmt != null) stmt.close();
                db.close(con);
            } catch (SQLException e) {
                System.out.println("Cleanup error: " + e.getMessage());
            }
        }
    
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        
        dbcon db = new dbcon();
        Connection con = null;
        PreparedStatement stmt = null;
        ResultSet rs = null;

        String userIdStr = username.getText().trim();
        if (userIdStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a User ID", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int userId;
        try {
            userId = Integer.parseInt(userIdStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "User ID must be a number", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            con = db.open();
            if (con == null) return;

            String query = "SELECT username, full_name, email FROM users WHERE user_id = ?";
            stmt = con.prepareStatement(query);
            stmt.setInt(1, userId);
            rs = stmt.executeQuery();

            if (rs.next()) {
                username4.setText(rs.getString("username"));
                username3.setText(rs.getString("full_name"));
                username2.setText(rs.getString("email"));
            } else {
                JOptionPane.showMessageDialog(this, "User not found", "ERROR", JOptionPane.ERROR_MESSAGE);
                clearFields();
            }
        } catch (SQLException e) {
            System.out.println("Search error: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Failed to search user: " + e.getMessage(), "ERROR", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) rs.close();
                if (stmt != null) stmt.close();
                db.close(con);
            } catch (SQLException e) {
                System.out.println("Cleanup error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

